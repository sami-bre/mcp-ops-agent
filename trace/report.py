"""Render run traces (runs/<id>/trace.jsonl) into a self-contained HTML report."""

from __future__ import annotations

import html
import json
from collections import Counter
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parent.parent
DEFAULT_RUNS_DIR = PROJECT_ROOT / "runs"

EVENT_COLORS = {
    "run_start": "#0b5cad",
    "llm_request": "#7a5ea8",
    "llm_response": "#7a5ea8",
    "tool_call": "#0b7a5c",
    "tool_result": "#3a6e3a",
    "guard_denied": "#b3261e",
    "run_finish": "#0b5cad",
}

TEMPLATE = """<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>mcp-ops-agent — agent trace report</title>
<style>
  body { font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, Helvetica, Arial, sans-serif;
         margin: 0; color: #1a1a1a; background: #fafafa; line-height: 1.55; }
  main { max-width: 52rem; margin: 0 auto; padding: 2.5rem 1.5rem 5rem; }
  h1 { font-size: 1.6rem; margin-bottom: 0.2rem; }
  .sub { color: #555; margin-top: 0; }
  .run { background: #fff; border: 1px solid #ddd; border-radius: 8px; padding: 1.2rem 1.4rem; margin: 1.4rem 0; }
  .run h2 { font-size: 1.05rem; margin: 0 0 0.4rem; border-bottom: 1px solid #e5e5e5; padding-bottom: 0.4rem; }
  .kv { color: #444; font-size: 0.92rem; }
  .answer { background: #f0f6f0; border-left: 3px solid #0b7a5c; padding: 0.5rem 0.8rem;
            margin: 0.6rem 0; font-size: 0.95rem; white-space: pre-wrap; }
  .err { background: #fdeceb; border-left: 3px solid #b3261e; padding: 0.5rem 0.8rem; margin: 0.6rem 0;
         font-size: 0.95rem; white-space: pre-wrap; }
  table.tl { width: 100%; border-collapse: collapse; margin-top: 0.6rem; font-size: 0.85rem; }
  table.tl td { padding: 0.35rem 0.5rem; border-top: 1px solid #eee; vertical-align: top; }
  td.ev { white-space: nowrap; font-weight: 600; }
  details { display: inline; }
  details > pre { display: block; margin: 0.4rem 0 0.2rem; padding: 0.6rem; background: #f4f4f2;
                  border-radius: 6px; overflow-x: auto; font-size: 0.78rem; white-space: pre-wrap;
                  word-break: break-word; }
  summary { cursor: pointer; color: #0b5cad; }
  .denied td { background: #fdeceb; }
  .badge { display: inline-block; font-size: 0.72rem; padding: 0.05rem 0.5rem; border-radius: 10px;
           color: #fff; margin-right: 0.4rem; }
  .tally { font-size: 0.85rem; color: #555; margin-top: 0.5rem; }
  footer { margin-top: 3rem; font-size: 0.82rem; color: #777; }
  code { background: #f0f0ee; padding: 0 0.25rem; border-radius: 3px; font-size: 0.85em; }
</style>
</head>
<body>
<main>
  <h1>mcp-ops-agent — trace report</h1>
  <p class="sub">Every LLM request/response and every tool call (args included), streamed
  from the LangGraph agent into an auditable JSONL trace. Guard denials are highlighted red.</p>
{runs}
  <footer>Generated by mcp-ops-agent · self-contained page, no external assets, no tracking</footer>
</main>
</body>
</html>
"""

RUN_TMPL = """<section class="run">
  <h2>{n}. {task_html}</h2>
  <p class="kv">provider: <code>{provider}</code> · steps: <b>{steps}</b> ·
     duration: <b>{duration}</b> · tools: {tally}</p>
{verdict}
  <table class="tl">{rows}
  </table>
</section>
"""


def _render_run(idx: int, run_dir: Path) -> str:
    trace_path = run_dir / "trace.jsonl"
    events = []
    with trace_path.open(encoding="utf-8") as fh:
        for line in fh:
            if line.strip():
                events.append(json.loads(line))
    if not events:
        return ""
    start = events[0]
    finish = next((e for e in reversed(events) if e["event"] == "run_finish"), None)
    task = html.escape(str(start["payload"].get("task", "(no task)")))
    provider = html.escape(f"{start['payload'].get('provider', '?')}"
                           f"/{start['payload'].get('model', '?')}")
    answer = (finish or {}).get("payload", {}).get("answer", "")
    error = (finish or {}).get("payload", {}).get("error", "") or \
            next((e["payload"].get("error") for e in events
                  if e["event"] == "run_finish" and e["payload"].get("error")), "")
    steps = sum(1 for e in events if e["event"] == "tool_call")
    duration = f"{(events[-1].get('elapsed_ms') or 0) / 1000:.1f}s"
    tally = Counter(e["payload"].get("tool", "?") for e in events
                    if e["event"] in ("tool_call", "guard_denied"))
    tally_html = ", ".join(f"<code>{html.escape(k)}</code> ×{v}"
                           for k, v in tally.most_common()) or "none"

    verdict = ""
    if error:
        verdict = f'<div class="err">error: {html.escape(str(error))}</div>'
    if answer:
        verdict += f'<div class="answer"><b>final answer:</b> {html.escape(str(answer))}</div>'

    rows = []
    for e in events:
        ev = e["event"]
        color = EVENT_COLORS.get(ev, "#666")
        payload = html.escape(json.dumps(e["payload"], ensure_ascii=False, indent=1))
        brief = html.escape(json.dumps(e["payload"], ensure_ascii=False)[:110])
        denied = ' class="denied"' if ev == "guard_denied" else ""
        rows.append(
            f'<tr{denied}><td>#{e["seq"]}</td>'
            f'<td class="ev"><span class="badge" style="background:{color}">{ev}</span></td>'
            f'<td><details><summary>{brief}</summary><pre>{payload}</pre></details></td></tr>')

    return RUN_TMPL.format(n=idx, task_html=task, provider=provider, steps=steps,
                           duration=duration, tally=tally_html,
                           verdict=verdict, rows="\n".join(rows))


def render(runs_dir: Path | None = None, out: Path | None = None) -> Path:
    runs_dir = Path(runs_dir) if runs_dir else DEFAULT_RUNS_DIR
    out = Path(out) if out else PROJECT_ROOT / "trace.html"
    run_dirs = sorted(p for p in runs_dir.iterdir()
                      if p.is_dir() and (p / "trace.jsonl").exists()) \
        if runs_dir.exists() else []
    if not run_dirs:
        body = "<p>No runs found. Run <code>make demo</code> first.</p>"
        out.write_text(TEMPLATE.replace("{runs}", body), encoding="utf-8")
        return out
    sections = "\n".join(_render_run(i + 1, d) for i, d in enumerate(run_dirs))
    out.write_text(TEMPLATE.replace("{runs}", sections), encoding="utf-8")
    return out


if __name__ == "__main__":
    import sys
    out = render()
    print(f"trace report written: {out}")